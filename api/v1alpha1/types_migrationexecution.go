// MigrationExecution is the per-target run. Created by the
// MigrationController from a MigrationPlan that passed admission.
type MigrationExecution struct {
	metav1.TypeMeta   `json:",inline"`
	metav1.ObjectMeta `json:"metadata,omitempty"`

	Spec   MigrationExecutionSpec   `json:"spec,omitempty"`
	Status MigrationExecutionStatus `json:"status,omitempty"`
}

// +kubebuilder:object:root=true

// MigrationExecutionList is the list wrapper required by client-go.
type MigrationExecutionList struct {
	metav1.TypeMeta `json:",inline"`
	metav1.ListMeta `json:"metadata,omitempty"`
	Items           []MigrationExecution `json:"items"`
}

func init() {
	SchemeBuilder.Register(&MigrationExecution{}, &MigrationExecutionList{})
}
